// Builds the landing page from its sources. Plain Node, standard library only (D12).
//   node site/build.mjs                       write site/styles.css, site/index.html, site/fonts/*
//   node site/build.mjs --check               exit 1 when a committed output differs from what the sources produce
//   node site/build.mjs --out DIR             write the site into DIR instead (scratch builds, never committed)
//   node site/build.mjs --shots DIR           take the screenshots listed in site/screenshots.json from DIR
//                                             (default docs/screenshots/release); a listed file that is missing is skipped
// Single sources of truth: colours, type, space and motion come from apps/web/design-tokens/tokens.json through the app's own
// generator (renderTokensCss); the fonts are the app's woff2 files; the repository URL is REPO_URL in site/repo-url.mjs (or $ABB_REPO_URL).
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadTokens, renderTokensCss } from "../apps/web/scripts/tokens-lib.mjs";

import { REPO_URL } from "./repo-url.mjs";

const SITE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.join(SITE, "..");
const FONT_SRC = path.join(REPO, "apps/web/src/fonts");
// Three faces are enough for the type scale (weights 400 and 600 in Sans, 400 in Mono). The app ships a fourth (Mono Medium) the page does not use.
const FONTS = ["IBMPlexSans-Regular-Latin1.woff2", "IBMPlexSans-SemiBold-Latin1.woff2", "IBMPlexMono-Regular-Latin1.woff2", "OFL.txt"];

const argv = process.argv.slice(2);
const flag = (name) => (argv.includes(name) ? argv[argv.indexOf(name) + 1] : undefined);
const check = argv.includes("--check");
const out = path.resolve(flag("--out") ?? SITE);
const shotsDir = path.resolve(flag("--shots") ?? path.join(REPO, "docs/screenshots/release"));

const FONT_FACES = `/* Self-hosted IBM Plex (SIL OFL 1.1, fonts/OFL.txt), Latin-1 subset copied from apps/web/src/fonts. Relative URLs keep the page working under a project sub-path. */
@font-face { font-family: "IBM Plex Sans"; font-weight: 400; font-style: normal; font-display: swap; src: url("fonts/IBMPlexSans-Regular-Latin1.woff2") format("woff2"); }
@font-face { font-family: "IBM Plex Sans"; font-weight: 600; font-style: normal; font-display: swap; src: url("fonts/IBMPlexSans-SemiBold-Latin1.woff2") format("woff2"); }
@font-face { font-family: "IBM Plex Mono"; font-weight: 400; font-style: normal; font-display: swap; src: url("fonts/IBMPlexMono-Regular-Latin1.woff2") format("woff2"); }
`;

/** PNG width and height from the IHDR chunk, so an <img> can reserve its space (no layout shift). */
function pngSize(file) {
  const b = readFileSync(file);
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
}

const escapeHtml = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function render() {
  const css = renderTokensCss(loadTokens()) + FONT_FACES + readFileSync(path.join(SITE, "src/site.css"), "utf8");
  const shots = JSON.parse(readFileSync(path.join(SITE, "screenshots.json"), "utf8"));
  const present = shots.filter((s) => existsSync(path.join(shotsDir, s.file)));
  const figures = present.map((s) => {
    const { w, h } = pngSize(path.join(shotsDir, s.file));
    return `        <figure class="shot">
          <img src="assets/shots/${s.file}" alt="${escapeHtml(s.alt)}" width="${w}" height="${h}" loading="lazy" decoding="async">
          <figcaption>${escapeHtml(s.caption)}</figcaption>
        </figure>`;
  });
  const gallery = figures.length
    ? `    <section class="band" id="screens" aria-labelledby="screens-h">
      <div class="wrap">
        <h2 id="screens-h">In the dashboard</h2>
        <div class="shots">
${figures.join("\n")}
        </div>
      </div>
    </section>
`
    : "";
  const html = readFileSync(path.join(SITE, "src/index.template.html"), "utf8")
    .replaceAll("{{REPO_URL}}", REPO_URL)
    .replace("<!--SCREENSHOTS-->\n", gallery);
  const banner = "<!-- generated by site/build.mjs from site/src/index.template.html: edit the template, not this file -->\n";
  return { css, html: html.replace("<!doctype html>\n", "<!doctype html>\n" + banner), present };
}

const { css, html, present } = render();
const outputs = [
  [path.join(out, "styles.css"), css],
  [path.join(out, "index.html"), html],
];
let stale = 0;
for (const [file, text] of outputs) {
  if (check) {
    const current = existsSync(file) ? readFileSync(file, "utf8") : "";
    if (current !== text) {
      stale++;
      console.error(`stale: ${path.relative(REPO, file)} (run \`node site/build.mjs\`)`);
    }
  } else {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
}
for (const f of FONTS) {
  const to = path.join(out, "fonts", f);
  if (check) {
    if (!existsSync(to) || !readFileSync(to).equals(readFileSync(path.join(FONT_SRC, f)))) {
      stale++;
      console.error(`stale: site/fonts/${f}`);
    }
  } else {
    mkdirSync(path.dirname(to), { recursive: true });
    copyFileSync(path.join(FONT_SRC, f), to);
  }
}
if (!check && present.length) {
  mkdirSync(path.join(out, "assets/shots"), { recursive: true });
  for (const s of present) copyFileSync(path.join(shotsDir, s.file), path.join(out, "assets/shots", s.file));
}
if (!check && out !== SITE) {
  // A scratch or deploy build (--out) gets the committed static assets too, so the directory is complete and holds no sources.
  mkdirSync(path.join(out, "assets"), { recursive: true });
  for (const f of readdirSync(path.join(SITE, "assets"), { withFileTypes: true })) {
    if (f.isFile()) copyFileSync(path.join(SITE, "assets", f.name), path.join(out, "assets", f.name));
  }
}
if (check && stale) process.exit(1);
if (!check) console.log(`wrote ${outputs.length} files, ${FONTS.length} font files, ${present.length} screenshots`);
