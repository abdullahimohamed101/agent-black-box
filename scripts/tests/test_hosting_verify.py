"""Self-test of scripts/hosting_verify_lib.py (Phase 23, A3). Run: python3 -m unittest discover -s scripts/tests -v

A verifier that cannot fail proves nothing. A small fake server stands in for the public origin: its well-behaved
mode must pass every assertion, and each planted defect (a missing HSTS, a public /metrics, a buffered event stream,
a forged-header evasion, a published port, a cookie without Secure, ...) must make the matching assertion FAIL.
The fake speaks TLS with a throwaway certificate generated by openssl into a temporary directory.
"""

