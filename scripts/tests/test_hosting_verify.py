def make_cert(directory: Path, name: str) -> Path:
    cert, key = directory / f"{name}.pem", directory / f"{name}.key"
    subprocess.run(  # noqa: S603
        ["openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-days", "1", "-subj", "/CN=localhost",
         "-addext", "subjectAltName=DNS:localhost,IP:127.0.0.1", "-keyout", str(key), "-out", str(cert)],
        check=True, capture_output=True, timeout=60,
    )  # fmt: skip
    return cert


class FakeOrigin:
    """The public origin as a client sees it, with optional planted defects."""

    def __init__(self, directory: Path, defects: Set[str]) -> None:
        self.defects = defects
        self.failed: Dict[str, int] = {}
        self.logins: Dict[str, int] = {}
        self.requests = 0
        self.junk = 0
        self.lock = threading.Lock()
        cert = directory / "server.pem"
        origin = self

        class Handler(BaseHTTPRequestHandler):
            protocol_version = "HTTP/1.0"  # the body ends when the connection closes: the client needs no chunk decoding

            def version_string(self) -> str:  # the stdlib default names Python's version, which the Server check would flag
                return "fake"

            def log_message(self, *args: object) -> None:  # noqa: D102
                pass

            def do_GET(self) -> None:  # noqa: N802
                origin.handle(self)

            def do_POST(self) -> None:  # noqa: N802
                origin.handle(self)

        ThreadingHTTPServer.daemon_threads = True  # an open fake stream must not hold up close()
        ThreadingHTTPServer.block_on_close = False
        self.tls = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        context.load_cert_chain(str(cert), str(directory / "server.key"))
        self.tls.socket = context.wrap_socket(self.tls.socket, server_side=True)
        self.plain = ThreadingHTTPServer(("127.0.0.1", 0), type("Plain", (Handler,), {}))
        self.plain.RequestHandlerClass.do_GET = lambda h: origin.plain_get(h)  # type: ignore[method-assign,assignment]
        self.threads = [threading.Thread(target=lambda s=s: s.serve_forever(poll_interval=0.05), daemon=True) for s in (self.tls, self.plain)]
        for t in self.threads:
            t.start()

    @property
    def tls_port(self) -> int:
        return self.tls.server_address[1]

    @property
    def plain_port(self) -> int:
        return self.plain.server_address[1]

    def close(self) -> None:
        for s in (self.tls, self.plain):
            s.shutdown()
            s.server_close()

    # ---- behaviour
    def plain_get(self, h: BaseHTTPRequestHandler) -> None:
        if "no_redirect" in self.defects:
            h.send_response(200)
            h.send_header("Content-Length", "2")
            h.end_headers()
            h.wfile.write(b"ok")
            return
        h.send_response(308)
        h.send_header("Location", "https://localhost" + h.path)
        h.send_header("Content-Length", "0")
        h.end_headers()

    def _common(self, h: BaseHTTPRequestHandler, api: bool) -> None:
        d = self.defects
        if not (("no_hsts_web" in d and not api) or ("no_hsts_api" in d and api)):
            h.send_header("Strict-Transport-Security", HSTS)
            if "hsts_twice_api" in d and api:
                h.send_header("Strict-Transport-Security", HSTS)
        if "no_nosniff" not in d:
            h.send_header("X-Content-Type-Options", "nosniff")
        h.send_header("X-Frame-Options", "DENY")
        if "x_powered_by" in d:
            h.send_header("X-Powered-By", "Next.js")
        if "server_version" in d:
            h.send_header("Server", "nginx/1.25.3")
        if api and "api_cacheable" not in d:
            h.send_header("Cache-Control", "no-store")

    def _send(self, h: BaseHTTPRequestHandler, status: int, body: bytes, ctype: str, api: bool = False, extra: Optional[List] = None) -> None:
        h.send_response(status)
        self._common(h, api)
        for k, v in extra or []:
            h.send_header(k, v)
        h.send_header("Content-Type", ctype)
        h.send_header("Content-Length", str(len(body)))
        h.end_headers()
        h.wfile.write(body)

    def _drain(self, h: BaseHTTPRequestHandler) -> int:
        remaining = total = int(h.headers.get("Content-Length") or 0)
        kept = b""
        while remaining > 0:
            data = h.rfile.read(min(remaining, 1 << 16))
            if not data:
                break
            remaining -= len(data)
            if total <= 4096:
                kept += data
        h.body = kept  # type: ignore[attr-defined]
        return total

    def handle(self, h: BaseHTTPRequestHandler) -> None:  # noqa: C901
        d = self.defects
        path = h.path.split("?")[0]
        peer = h.client_address[0]
        with self.lock:
            self.requests += 1
            count = self.requests
        length = self._drain(h) if h.command == "POST" else 0
        if path == "/healthz":
            if "health_down_in_flood" in d and count > 12:
                return self._send(h, 503, b"{}", "application/json", api=True)
            return self._send(h, 200, b'{"status":"ok","version":"0"}', "application/json", api=True)
        if path == "/":
            nonce = "constantnonce" if "static_nonce" in d else os.urandom(9).hex()
            script = f"'self' 'nonce-{nonce}' 'strict-dynamic'" + (" 'unsafe-inline'" if "unsafe_inline" in d else "")
            csp = f"default-src 'self'; script-src {script}; frame-ancestors 'none'"
            page_nonce = "different" if "nonce_mismatch" in d else nonce
            body = f'<html><script nonce="{page_nonce}" src="/_next/static/chunks/app.js"></script></html>'.encode()
            return self._send(h, 200, body, "text/html", extra=[("Content-Security-Policy", csp)])
        if path == "/_next/static/chunks/app.js":
            js = b"function f(){return 1}\n" * 2000
            if "gzip" in (h.headers.get("Accept-Encoding") or "") and "no_gzip" not in d:
                return self._send(h, 200, gzip.compress(js), "text/javascript", extra=[("Content-Encoding", "gzip")])
            return self._send(h, 200, js, "text/javascript")
        if path in ("/docs", "/redoc", "/openapi.json", "/readyz", "/metrics"):
            public = {"docs_public": "/docs", "readyz_public": "/readyz", "metrics_public": "/metrics"}
            if any(flag in d and path == p for flag, p in public.items()):
                return self._send(h, 200, b"{}", "application/json", api=True)
            if "metrics_token_only" in d and path == "/metrics" and TOKEN in (h.headers.get("Authorization") or ""):
                return self._send(h, 200, b"# metrics", "text/plain", api=True)
            return self._send(h, 404, b'{"detail":"Not Found"}', "application/json", api=True)
        if path == "/v1/me":
            if "__Host-abb_session=sess" in (h.headers.get("Cookie") or "") and "session_refused" not in d:
                return self._send(h, 200, b'{"user":{"id":"usr_x"}}', "application/json", api=True)
            return self._send(h, 401, b'{"error":{"code":"UNAUTHENTICATED"}}', "application/json", api=True,
                              extra=[("Content-Security-Policy", "default-src 'none'; frame-ancestors 'none'")])  # fmt: skip
        if path == "/v1/runs":
            key = peer
            if "xff_trusted" in d:
                key = (h.headers.get("X-Forwarded-For") or peer).split(",")[0].strip()
            with self.lock:
                self.failed[key] = self.failed.get(key, 0) + 1
                over = self.failed[key] > 30 and "no_throttle" not in d
            if over:
                extra = [] if "no_retry_after" in d else [("Retry-After", "7")]
                return self._send(h, 429, b'{"error":{"code":"AUTH_THROTTLED"}}', "application/json", api=True, extra=extra)
            return self._send(h, 401, b'{"error":{"code":"UNAUTHENTICATED"}}', "application/json", api=True)
        if path == "/v1/events/batch":
            limit = 512 * 1024 if "low_body_limit" in d else 8 * 1024 * 1024
            if length > limit and "no_body_limit" not in d:
                return self._send(h, 413, b"", "text/plain")
            return self._send(h, 401, b'{"error":{"code":"UNAUTHENTICATED"}}', "application/json", api=True)
        if path == "/api/auth/login":
            with self.lock:
                self.logins[peer] = self.logins.get(peer, 0) + 1
                over = self.logins[peer] > 10 and "no_flood_limit" not in d
            h.send_response(302)
            if over:
                h.send_header("Location", "/login?error=rate_limited")
                h.send_header("Retry-After", "30")
            else:
                host = h.headers.get("Host") or "localhost"
                h.send_header("Location", f"https://{host}/authorize?client_id=x&state=s1&redirect_uri=https%3A%2F%2F{host}%2Fapi%2Fauth%2Fcallback")
                attrs = "Path=/; SameSite=Lax"
                if "cookie_no_secure" not in d:
                    attrs += "; Secure"
                if "cookie_no_httponly" not in d:
                    attrs += "; HttpOnly"
                if "cookie_domain" in d:
                    attrs += "; Domain=example.org"
                if "cookie_wrong_path" in d:
                    attrs = attrs.replace("Path=/", "Path=/api")
                h.send_header("Set-Cookie", f"__Host-abb_login=secretvalue; {attrs}")
            self._common(h, False)
            h.send_header("Content-Length", "0")
            h.end_headers()
            return
        if path == "/authorize":
            if h.command == "GET":
                page = (
                    '<form method="post"><input type="hidden" name="state" value="s1">'
                    '<input type="hidden" name="redirect_uri" value="https://x/cb"><input name="email"></form>'
                )
                return self._send(h, 200, page.encode(), "text/html")
            email = parse_qs(getattr(h, "body", b"").decode()).get("email", [""])[0]
            code = "stranger" if email.startswith("stranger") else "invited"
            host = h.headers.get("Host") or "localhost"
            h.send_response(302)
            h.send_header("Location", f"https://{host}/api/auth/callback?code={code}&state=s1")
            h.send_header("Content-Length", "0")
            h.end_headers()
            return
        if path == "/api/auth/callback":
            code = parse_qs(h.path.partition("?")[2]).get("code", [""])[0]
            h.send_response(302)
            if "__Host-abb_login=" not in (h.headers.get("Cookie") or ""):
                h.send_header("Location", "/login?error=login_failed")
            elif code == "stranger" and "stranger_gets_session" not in d:
                h.send_header("Location", "/login?error=no_access")
            else:
                h.send_header("Location", "/")
                attrs = "Path=/; SameSite=Lax; HttpOnly"
                if "session_no_secure" not in d:
                    attrs += "; Secure"
                if "session_domain" in d:
                    attrs += "; Domain=example.org"
                h.send_header("Set-Cookie", f"__Host-abb_session=sess; {attrs}")
            h.send_header("Content-Length", "0")
            h.end_headers()
            return
        if path == "/api/abb/v1/me":
            cookie = h.headers.get("Cookie") or ""
            with self.lock:
                if "__Host-abb_session=sess" not in cookie:
                    self.junk += 1
            if "__Host-abb_session=sess" in cookie:
                if "relay_locks_out_valid" in d and self.junk > 30:
                    return self._send(h, 429, b"{}", "application/json", api=True)
                return self._send(h, 200, b'{"memberships":[{"workspace":{"id":"ws_x","slug":"s"}}]}', "application/json", api=True)
            return self._send(h, 401, b"{}", "application/json", api=True)
        if path in ("/v1/runs/run1/stream", "/api/abb/v1/runs/run1/stream"):
            via_relay = path.startswith("/api/abb")
            credential = "__Host-abb_session=sess" in (h.headers.get("Cookie") or "") if via_relay else TOKEN in (h.headers.get("Authorization") or "")
            if not credential:
                return self._send(h, 401, b"{}", "application/json", api=True)
            if via_relay and (h.headers.get("X-ABB-Workspace") or "") != "ws_x":
                return self._send(h, 400, b"{}", "application/json", api=True)
            h.send_response(200)
            h.send_header("Content-Type", "text/event-stream")
            h.send_header("Cache-Control", "no-store")
            if "sse_gzip" in d:
                h.send_header("Content-Encoding", "gzip")
            h.end_headers()
            try:
                if "buffered_sse" in d:
                    time.sleep(6)  # what a proxy that waits for its buffer to fill looks like to the client
                h.wfile.write(b"retry: 3000\n\n: open\n\n")
                h.wfile.flush()
                for _ in range(40):
                    time.sleep(HEARTBEAT)
                    if "no_heartbeat" in d:
                        continue
                    h.wfile.write(b": keepalive\n\n")
                    h.wfile.flush()
            except (BrokenPipeError, ConnectionResetError, ssl.SSLError):
                pass
            return
        return self._send(h, 404, b"{}", "application/json", api=True)


class Base(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        if shutil.which("openssl") is None:
            raise unittest.SkipTest("openssl is required for the TLS fake")
        cls.dir = Path(tempfile.mkdtemp(prefix="hosting-verify-test-"))
        make_cert(cls.dir, "server")
        make_cert(cls.dir, "other")

    @classmethod
    def tearDownClass(cls) -> None:
        shutil.rmtree(cls.dir, ignore_errors=True)

    def run_with(self, defects: Set[str], fn: Callable[[lib.Target, lib.Options], List[lib.Result]], cacert: Optional[Path] = None) -> Dict[str, lib.Result]:
        origin = FakeOrigin(self.dir, defects)
        self.addCleanup(origin.close)
        target = lib.Target(f"https://localhost:{origin.tls_port}", str(cacert or self.dir / "server.pem"), "127.0.0.1", origin.plain_port, timeout=10)
        opts = lib.Options(
            metrics_token=TOKEN, stream_path="/v1/runs/run1/stream", stream_token=TOKEN,
            signin_email="alice@example.test", signin_stranger="stranger@example.test",
            first_bound=3.0, heartbeat_bound=4.0, over_limit_bytes=9 * 1024 * 1024, under_limit_bytes=7 * 1024 * 1024,
        )  # fmt: skip
        return {r.check: r for r in fn(target, opts)}


