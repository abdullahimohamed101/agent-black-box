class WellBehavedOrigin(Base):
    def test_every_assertion_passes_against_a_correct_origin(self) -> None:
        results = self.run_with(set(), lambda t, o: lib.run_checks(t, o))
        failed = {k: v.detail for k, v in results.items() if v.status != "PASS"}
        self.assertEqual(failed, {})
        # The names below are the assertions A3/A5 promise; an accidental rename or deletion shows here.
        for name in ("tls.certificate", "tls.http_redirect", "headers.hsts_once.web", "headers.csp_nonce_changes",
                     "paths.metrics_not_public", "auth.login_cookie", "xff.forged_header_cannot_evade_throttle",
                     "sse.first_event", "sse.heartbeat", "body.over_limit_refused_413", "compress.static_asset",
                     "flood.signin_start_limited", "signin.invited_person", "signin.stranger_refused", "relay.me_through_web", "relay.stream_through_web",
                     "relay.junk_flood_keeps_valid_session"):  # fmt: skip
            self.assertIn(name, results)

    def test_a_certificate_from_another_ca_fails(self) -> None:
        results = self.run_with(set(), GROUPS["tls"], cacert=self.dir / "other.pem")
        self.assertEqual(results["tls.certificate"].status, "FAIL")

    def test_missing_stream_inputs_skip_instead_of_passing(self) -> None:
        results = self.run_with(set(), lambda t, o: lib.check_stream(t, lib.Options()))
        self.assertEqual(results["sse.first_event"].status, "SKIP")


def _planted_case(defect: str, group: str, check: str) -> Callable[[Base], None]:
    def test(self: Base) -> None:
        results = self.run_with({defect}, GROUPS[group])
        self.assertEqual(results[check].status, "FAIL", f"{defect} was not noticed by {check}: {results[check].detail}")
        others = [r.check for r in results.values() if r.status == "FAIL" and r.check != check]
        # Several checks may legitimately notice one defect (e.g. nosniff on web and api), but a defect in one
        # area must not turn unrelated assertions red: that would hide which assertion is doing the work.
        self.assertLessEqual(len(others), 1, f"{defect} also failed {others}")

    return test


class PlantedViolations(Base):
    pass


for _defect, _group, _check in PLANTED:
    setattr(PlantedViolations, f"test_{_defect}_fails_{_check.replace('.', '_')}", _planted_case(_defect, _group, _check))


def good_config() -> dict:
    env = {"ABB_ENVIRONMENT": "production"}
    web_env = {"ABB_WEB_ORIGIN": "https://abb.example.org", "ABB_TRUST_PROXY": "1"}
    api_env = dict(env, **web_env, ABB_OIDC_ISSUER="https://accounts.google.com", ABB_CORS_ORIGINS="https://abb.example.org",
                   ABB_ALLOW_DEV_SESSIONS="0")  # fmt: skip
    keep = {"restart": "unless-stopped", "mem_limit": "1"}
    return {
        "services": {
            "postgres": dict(keep, networks={"default": None}),
            "migrate": {"environment": dict(env)},
            "api": dict(keep, environment=api_env, networks={"default": None, "edge": None}),
            "worker": dict(keep, environment=dict(env)),
            "retention": dict(keep, environment=dict(env)),
            "web": dict(keep, environment=web_env, networks={"default": None, "edge": None}),
        }
    }


def mutated(change: Callable[[dict], None]) -> dict:
    cfg = json.loads(json.dumps(good_config()))
    change(cfg)
    return cfg


